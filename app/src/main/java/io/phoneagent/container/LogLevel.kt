package io.phoneagent.container

/**
 * 一条诊断信息的严重程度。
 *
 * 存在的理由：界面上曾经把所有日志都渲染成红色 —— 于是一句
 * 「已从交互目录取回 3 个文件」看起来和「pty 建不起来」一模一样。
 * 严重程度必须是数据的一部分，不能靠调用点各自决定怎么显示。
 */
enum class LogLevel {
    /** 进度与状态，正常流程会出现的。界面上短暂显示后自动消失。 */
    INFO,

    /** 有问题但不致命（比如某次同步失败）。留在界面上等用户处理。 */
    WARN,

    /** 真的坏了。留在界面上，需要用户主动关掉。 */
    ERROR,
}
